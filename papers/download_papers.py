"""Download the papers listed in papers.yaml and check their titles.

Usage::

    uv run python papers/download_papers.py [--force] [--only KEY [KEY ...]]

- Idempotent: a PDF already on disk whose first page matches the expected title is kept.
- PDFs go to ``papers/pdf/<year>_<acronym>_<short_title>.pdf`` (git-ignored), downloaded from
  ``https://arxiv.org/pdf/<arxiv_id><version>`` (the version is pinned in papers.yaml).
- The title found on the first page is compared with the expected title, after Unicode and
  punctuation normalisation.
- Failures are appended to ``papers/pdf/download.log`` and summarised; the exit code is 1 if
  any paper failed.
- The table section of ``papers/README.md`` (between the BEGIN/END markers) is regenerated
  with the download status.
"""

from __future__ import annotations

import argparse
import datetime as dt
import difflib
import sys
import time
import unicodedata
import urllib.request
from dataclasses import dataclass
from pathlib import Path

import yaml
from pypdf import PdfReader

HERE = Path(__file__).resolve().parent
PDF_DIR = HERE / "pdf"
README = HERE / "README.md"
LOG = PDF_DIR / "download.log"
TABLE_BEGIN = "<!-- BEGIN papers-table (generated by download_papers.py, do not edit) -->"
TABLE_END = "<!-- END papers-table -->"
USER_AGENT = "ovannot-papers/0.1 (research testbed; polite single-threaded downloads)"
DELAY_S = 3.0  # arXiv asks automated clients to space their requests
GROUP_ORDER = {"main": 0, "complementary": 1, "task1": 2}


@dataclass
class Result:
    key: str
    ok: bool
    status: str  # short text shown in the README table


def pdf_path(paper: dict) -> Path:
    return PDF_DIR / f"{paper['year']}_{paper['acronym']}_{paper['short_title']}.pdf"


def normalise(text: str) -> str:
    """Lowercase alphanumerics only, with ligatures and accents decomposed."""
    text = unicodedata.normalize("NFKD", text)
    return "".join(c for c in text.lower() if c.isalnum() and c.isascii())


def title_matches(expected: str, first_page: str, min_ratio: float = 0.9) -> bool:
    """Exact match of the normalised title in the normalised page, else a fuzzy match on the
    best window of the same length (PDF text extraction sometimes garbles a character)."""
    title, page = normalise(expected), normalise(first_page)
    if not title or title in page:
        return bool(title)
    n = len(title)
    best = max(
        (
            difflib.SequenceMatcher(None, title, page[i : i + n]).ratio()
            for i in range(0, max(1, len(page) - n + 1))
        ),
        default=0.0,
    )
    return best >= min_ratio


def first_page_text(path: Path) -> str:
    return PdfReader(path).pages[0].extract_text() or ""


def download(url: str, dest: Path) -> None:
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=120) as response:
        data = response.read()
    if not data.startswith(b"%PDF"):
        raise ValueError(f"not a PDF (got {len(data)} bytes starting with {data[:20]!r})")
    tmp = dest.with_suffix(".part")
    tmp.write_bytes(data)
    tmp.replace(dest)


def log(message: str) -> None:
    PDF_DIR.mkdir(parents=True, exist_ok=True)
    stamp = dt.datetime.now().isoformat(timespec="seconds")
    with LOG.open("a", encoding="utf-8") as f:
        f.write(f"{stamp} {message}\n")


def fetch(paper: dict, force: bool) -> tuple[Result, bool]:
    """Ensure the PDF is present and checked. Returns the result and whether it downloaded."""
    dest = pdf_path(paper)
    url = f"https://arxiv.org/pdf/{paper['arxiv_id']}{paper['version']}"
    downloaded = False
    if force or not dest.exists():
        try:
            download(url, dest)
            downloaded = True
        except Exception as exc:
            log(f"FAIL download {paper['key']} {url}: {exc}")
            return Result(paper["key"], False, f"download failed ({type(exc).__name__})"), True
    try:
        text = first_page_text(dest)
    except Exception as exc:
        log(f"FAIL read {paper['key']} {dest.name}: {exc}")
        return Result(paper["key"], False, "unreadable PDF"), downloaded
    if not title_matches(paper["title"], text):
        log(f"FAIL title {paper['key']} {dest.name}: first page starts with {text[:200]!r}")
        return Result(paper["key"], False, "title mismatch"), downloaded
    return Result(paper["key"], True, f"ok ({paper['version']}, title checked)"), downloaded


def render_table(papers: list[dict], results: dict[str, Result]) -> str:
    rows = [
        "| Group | Title | Year | Venue | Link | Role in the project | Download |",
        "|---|---|---|---|---|---|---|",
    ]
    for p in sorted(papers, key=lambda p: GROUP_ORDER.get(p["group"], 9)):
        res = results.get(p["key"])
        status = res.status if res else "not attempted"
        link = f"[arXiv:{p['arxiv_id']}{p['version']}](https://arxiv.org/abs/{p['arxiv_id']}{p['version']})"
        title = p["title"].replace("|", "\\|")
        rows.append(
            f"| {p['group']} | [{title}](#{p['key']}) | {p['year']} | {p['venue']} | {link} "
            f"| {p['role']} | {status} |"
        )
    return "\n".join(rows)


def update_readme(table: str) -> bool:
    if not README.exists():
        return False
    text = README.read_text(encoding="utf-8")
    start, end = text.find(TABLE_BEGIN), text.find(TABLE_END)
    if start < 0 or end < start:
        return False
    new = text[: start + len(TABLE_BEGIN)] + "\n" + table + "\n" + text[end:]
    README.write_text(new, encoding="utf-8")
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--force", action="store_true", help="re-download even if present")
    parser.add_argument("--only", nargs="+", metavar="KEY", help="restrict to these paper keys")
    args = parser.parse_args(argv)

    papers = yaml.safe_load((HERE / "papers.yaml").read_text(encoding="utf-8"))["papers"]
    selected = [p for p in papers if not args.only or p["key"] in args.only]
    PDF_DIR.mkdir(parents=True, exist_ok=True)

    results: dict[str, Result] = {}
    for i, paper in enumerate(selected):
        result, downloaded = fetch(paper, args.force)
        results[paper["key"]] = result
        print(f"[{'ok' if result.ok else 'FAIL'}] {paper['key']}: {result.status}")
        if downloaded and i < len(selected) - 1:
            time.sleep(DELAY_S)

    if not args.only:  # the table must reflect every paper
        if update_readme(render_table(papers, results)):
            print(f"updated the table in {README.relative_to(HERE.parent)}")
        else:
            print(f"warning: no table markers in {README}; table not written", file=sys.stderr)

    failed = [k for k, r in results.items() if not r.ok]
    if failed:
        print(f"{len(failed)} failure(s): {', '.join(failed)} (details in {LOG})", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
