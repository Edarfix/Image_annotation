"""Regenerate the leaderboard from the runs' metrics.json files (never edit it by hand).

Usage::

    uv run python scripts/make_leaderboard.py

Reads ``results/runs/*/metrics.json`` and keeps, for each (pipeline, dataset group, setting,
subset), the latest run. Writes:

- ``results/leaderboard.md``: one row per pipeline and dataset, plus the mean of each run;
- the index section of ``pipelines/README.md`` (one line per pipeline: best mean mAP);
- section 9 of each pipeline README (its own rows).

Settings and subsets are never mixed in one table (README, "Reading the leaderboard").
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))  # run as a script, the package may not be installed

from ovannot.utils.io import read_json  # noqa: E402

RUN_NAME = re.compile(r"^(?P<date>\d{4}-\d{2}-\d{2})_(?P<pipeline>.+)_(?P<hash>[0-9a-f]{8})$")
HEADER = (
    "| Pipeline | Dataset | Domain | Images | mAP | AP50 | P@0.5 | R@0.5 | F1@0.5 "
    "| s/img mean | s/img p95 | calls/img | failures | Run |"
)
RULE = "|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|"


def latest_runs(runs_root: Path) -> list[tuple[Path, dict]]:
    by_key: dict[tuple, tuple[Path, dict]] = {}
    for path in sorted(runs_root.glob("*/metrics.json")):
        if not RUN_NAME.match(path.parent.name):
            continue
        m = read_json(path)
        key = (m["pipeline"], m["dataset_group"], m["setting"], m["subset"])
        by_key[key] = (path.parent, m)  # sorted by name, which starts with the date
    return [by_key[k] for k in sorted(by_key)]


def pct(x: float) -> str:
    return f"{100 * x:.1f}"


def rows(run_dir: Path, m: dict) -> list[str]:
    out = []
    for name, d in m["per_dataset"].items():
        c = d["cost"]
        out.append(
            f"| `{m['pipeline']}` | {name} | {d['domain']} | {d['n_images']} | {pct(d['mAP'])} "
            f"| {pct(d['AP50'])} | {pct(d['precision@0.5'])} | {pct(d['recall@0.5'])} "
            f"| {pct(d['f1@0.5'])} | {c['time_per_image_s']['mean']:.2f} "
            f"| {c['time_per_image_s']['p95']:.2f} | {c['model_calls_per_image']:.1f} "
            f"| {pct(d['failure_rate'])}% | `{run_dir.name}` |"
        )
    mean = m["mean"]
    out.append(
        f"| `{m['pipeline']}` | **mean of {len(m['per_dataset'])}** | | | **{pct(mean['mAP'])}** "
        f"| {pct(mean['AP50'])} | {pct(mean['precision@0.5'])} | {pct(mean['recall@0.5'])} "
        f"| {pct(mean['f1@0.5'])} | | | | | |"
    )
    return out


def tables(runs: list[tuple[Path, dict]], pipeline: str | None = None) -> str:
    sections: dict[tuple[str, str], list[str]] = {}
    for run_dir, m in runs:
        if pipeline is None or m["pipeline"] == pipeline:
            sections.setdefault((m["setting"], m["subset"]), []).extend(rows(run_dir, m))
    if not sections:
        return "_No run yet._"
    parts = []
    for (setting, subset), lines in sorted(sections.items()):
        parts.append(f"**Setting `{setting}`, subset `{subset}`** (metrics in %)\n")
        parts.append("\n".join([HEADER, RULE, *lines]) + "\n")
    return "\n".join(parts).strip()


def replace_block(path: Path, name: str, body: str) -> None:
    text = path.read_text(encoding="utf-8")
    pattern = re.compile(rf"(<!-- BEGIN {name}[^\n]*-->\n).*?(<!-- END {name} -->)", re.S)
    if not pattern.search(text):
        raise SystemExit(f"{path}: no '{name}' block")
    path.write_text(pattern.sub(lambda mt: mt.group(1) + body + "\n" + mt.group(2), text))


def main() -> int:
    runs = latest_runs(ROOT / "results" / "runs")
    board = ROOT / "results" / "leaderboard.md"
    board.write_text(
        "# Leaderboard\n\n"
        "Generated by `scripts/make_leaderboard.py` from `results/runs/*/metrics.json`; never "
        "edit by hand. How to read it: [README](../README.md#reading-the-leaderboard).\n\n"
        + tables(runs)
        + "\n",
        encoding="utf-8",
    )
    best: dict[str, tuple[float, str]] = {}
    for _, m in runs:
        label = f"{m['setting']}, {m['subset']}"
        if m["pipeline"] not in best or m["mean"]["mAP"] > best[m["pipeline"]][0]:
            best[m["pipeline"]] = (m["mean"]["mAP"], label)
    index = ["| Pipeline | Best mean mAP | Setting, subset |", "|---|---:|---|"]
    index += [f"| [`{p}`]({p}/) | {pct(v)} | {lbl} |" for p, (v, lbl) in sorted(best.items())]
    replace_block(
        ROOT / "pipelines" / "README.md",
        "pipelines-index",
        "\n".join(index) if best else "_No pipeline has been run yet._",
    )
    for readme in sorted((ROOT / "pipelines").glob("[!_]*/README.md")):
        replace_block(readme, "results", tables(runs, readme.parent.name))
    print(f"{len(runs)} run(s) -> {board.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
